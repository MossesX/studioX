/**
 * @file The gizmox-brand import — 728 `file:` entries inlined to `svg:` DATA.
 *
 * Reads the STAGED copy of GizmoX's installed branding package
 * (`pre-build/assets/import/branding/gizmox-brand/` — staged so the import stays
 * reproducible after the port, when GizmoX may not be on the machine at all;
 * the installed dir, never the archive zip, is the source of record) and emits
 * `src/packs/axs-studio-brand.entries.json`: every entry with its SVG inlined,
 * because AmberX packs are filesystem-free and because an entry without inline
 * SVG is one `checkCoverage` cannot measure.
 *
 * 453 of those entries are GizmoX's own 0.1.0 output. The other 275 are the
 * brand extension — 50 animated icons, 25 badges, 50 animated badges, and 150
 * lettered logos carrying the six house names — composed into the same staged
 * pack by `scripts/gen-brand-extension.mjs`, which owns every file it writes.
 * The staged pack is 0.2.0 from that point on; the import does not care which
 * generator drew a file, only that it obeys the same rules.
 *
 * Assertions, not conventions — the script REFUSES rather than emits on:
 *   - an entry count other than 728 (453 base + 275 extension; the base half is
 *     [P0-VERIFIED], MASTER §6.1);
 *   - a missing or unreadable SVG file;
 *   - a bare `fill`/`stroke`/`stop-color` hex outside a `var()` fallback.
 *     Themeable is the requirement, not a side effect: every drawing must still
 *     paint through a role variable AFTER the import. GizmoX's predecessor
 *     shipped 453 SVGs *capable* of recolouring that never did; this check is
 *     what stops that recurring one import later.
 *
 * Rerunnable: same input, same output, byte for byte.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const STAGED = resolve(here, "../../../assets/import/branding/gizmox-brand");
const OUT = resolve(here, "../src/packs/axs-studio-brand.entries.json");

if (!existsSync(join(STAGED, "manifest.json"))) {
  console.error(`REFUSED: no staged pack at ${STAGED} — stage the installed dir first.`);
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(join(STAGED, "manifest.json"), "utf-8"));
const entries = manifest.payload.entries;

const EXPECTED = 728;
if (entries.length !== EXPECTED) {
  console.error(`REFUSED: expected ${EXPECTED} entries, found ${entries.length} — wrong source, ` +
    "or the extension generator has not been re-run (npm run gen:brand-ext)?");
  process.exit(1);
}

/** A paint attribute whose value starts with a hex/rgb literal (not `var(`). */
const BARE_PAINT =
  /(?:fill|stroke|stop-color)\s*[:=]\s*"?\s*(?:#[0-9a-fA-F]{3,8}\b|rgba?\()/g;

const faults = [];
const inlined = entries.map((entry) => {
  const path = join(STAGED, entry.file);
  if (!existsSync(path)) {
    faults.push(`${entry.id}: file missing (${entry.file})`);
    return entry;
  }
  const svg = readFileSync(path, "utf-8").trim();
  for (const hit of svg.matchAll(BARE_PAINT)) {
    // A hex INSIDE a var() fallback is fine: `var(--gxb-accent, #ff7a1a)`.
    // Those never match here because the attribute value starts with `var(`,
    // not with the hex — so any match at all is a genuinely bare paint.
    faults.push(`${entry.id}: bare paint "${hit[0]}"`);
  }
  if (!/viewBox="/.test(svg)) faults.push(`${entry.id}: no viewBox — unmeasurable`);
  // `file` is dropped: the emitted pack is filesystem-free, and a surviving
  // file path is an invitation for a consumer to read it.
  const { file, ...rest } = entry;
  return { ...rest, svg };
});

if (faults.length) {
  console.error(`REFUSED — ${faults.length} fault(s):`);
  for (const f of faults) console.error("  -", f);
  process.exit(1);
}

const out = {
  "//": [
    "GENERATED by scripts/import-gizmox-brand.mjs — do not edit by hand.",
    "Source: pre-build/assets/import/branding/gizmox-brand/ (staged copy of",
    "GizmoX's installed pack at 453 entries, plus the 275-drawing brand",
    "extension from scripts/gen-brand-extension.mjs = 728). Every entry's SVG",
    "is inlined and asserted free of bare paint hexes outside var() fallbacks.",
    "The Amber contract overlay is merged in src/packs/axs-studio.ts, not here."
  ],
  source: "gizmox-brand 0.2.0 (installed dir, staged; 453 base + 275 extension)",
  count: inlined.length,
  entries: inlined
};

writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n", "utf-8");
console.log(`OK: ${inlined.length} entries inlined, zero bare paints -> ${OUT}`);
